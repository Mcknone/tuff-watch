def png(w, h, layer, t):
    im = Image.new('RGBA', (w, h), (0,0,0,0)); d = ImageDraw.Draw(im)
    k = DATES.index(t) if t in DATES else 2
    frac = (k+1)/len(DATES)
    if 'Radiometric' in layer:
        d.rectangle([0,0,w,h], fill=(150,150,150,255))
        d.rectangle([0,0,int(w*0.4*frac),h], fill=(150-int(90*frac),)*3+(255,))
    elif 'Thermal' in layer:
        for i in range(6): d.ellipse([int(w*0.3)+i*7,int(h*0.4),int(w*0.3)+4+i*7,int(h*0.4)+4], fill=(255,0,0,255))
    out = io.BytesIO(); im.save(out, 'PNG'); return out.getvalue()

def near_merauke(bbox):
    w, s, e, n = bbox
    return w < 140.6 and e > 140.2 and s < -8.1 and n > -8.5

RASTER_PRODUCTS = {'OPERA_L3_DIST-ALERT-HLS_V1', 'OPERA_L3_DSWX-S1_V1', 'OPERA_L3_DSWX-HLS_V1'}

def api(route):
    url = urllib.parse.urlparse(route.request.url); q = dict(urllib.parse.parse_qsl(url.query))
    requests.append(url.path + '?' + url.query)
    if url.path == '/api/health': return route.fulfill(json={'ok': True})
    if url.path == '/api/cmr/granules':
        name = q['short_name']
        bbox = [float(v) for v in q['bbox'].split(',')]
        if q.get('bands'):
            bands = q['bands'].split(',')
            if 'MCDWD' in name: return route.fulfill(status=502, json={'error': 'CMR HTTP 503', 'kind': 'http'})
            if name not in RASTER_PRODUCTS or not near_merauke(bbox):
                return route.fulfill(json={'hits':0,'returned':0,'truncated':False,'pages':1,'dates':[],'collections':[],'collectionInfo':[],'granules':[],'sample':[],'query':'https://cmr.example/q'})
            granules = [{'id': f'G{i}', 'title': f'{name}_T54LXX_{d}', 'start': d + 'T01:00:00Z', 'date': d, 'collection': 'C1',
                         'links': [f'https://data.lpdaac.earthdatacloud.nasa.gov/fixture/{name}_{d}_{b}.tif' for b in bands]} for i, d in enumerate(DATES)]
            return route.fulfill(json={'hits': len(granules), 'returned': len(granules), 'truncated': False, 'pages': 1, 'dates': DATES, 'collections': ['C1'],
                                       'collectionInfo': [{'id': 'C1', 'shortName': name, 'version': '1'}], 'granules': granules, 'sample': [],
                                       'query': 'https://cmr.earthdata.nasa.gov/search/granules.json?short_name=' + name})
        if 'NISAR' in name: return route.fulfill(json={'hits':0,'returned':0,'dates':[],'collections':[],'sample':[],'query':'https://cmr.example/q'})
        if 'MODISA' in name: return route.fulfill(status=502, json={'error':'CMR HTTP 503'})
        return route.fulfill(json={'hits':len(DATES)*3,'returned':len(DATES)*3,'dates':DATES,'collections':['C1'],'sample':[],'query':'https://cmr.earthdata.nasa.gov/search/granules.json?short_name='+name})
    if url.path == '/api/data':
        if MODE['data'] == 'auth':
            return route.fulfill(status=401, json={'error': 'NASA Earthdata refused access (HTTP 401)', 'kind': 'auth'})
        name = os.path.basename(urllib.parse.urlparse(q['url']).path)
        path = os.path.join(FIX, name)
        if not os.path.exists(path): return route.fulfill(status=502, json={'error': 'NASA data server HTTP 404', 'kind': 'http'})
        data = open(path, 'rb').read()
        rng = route.request.headers.get('range')
        if rng:
            a, b = rng.replace('bytes=', '').split('-')
            a = int(a); b = min(int(b) if b else len(data) - 1, len(data) - 1)
            return route.fulfill(status=206, body=data[a:b + 1], headers={'content-type': 'image/tiff', 'content-range': f'bytes {a}-{b}/{len(data)}', 'accept-ranges': 'bytes'})
        return route.fulfill(body=data, headers={'content-type': 'image/tiff'})
    if url.path.startswith('/api/gibs/colormap/'):
        return route.fulfill(status=404, json={'error':'NASA HTTP 404'})
    if url.path == '/api/gibs/wms':
        w, h = int(q['WIDTH']), int(q['HEIGHT'])
        if q.get('proj') != '3857':
            bbox = [float(v) for v in q['BBOX'].split(',')]
            assert bbox[0] < bbox[2] and bbox[1] < bbox[3] and abs(bbox[0]) <= 90 and abs(bbox[2]) <= 90, 'WMS 1.3.0 lat,lon order expected'
        return route.fulfill(body=png(w,h,q['LAYERS'],q.get('TIME','')), content_type='image/png')
    route.fulfill(status=404, json={'error':'?'})

def wait_done(page, timeout=90000):
    page.wait_for_function("document.querySelector('#analyze').disabled === false && /Analysis complete|No usable|outdated/.test(document.querySelector('#status').textContent)", timeout=timeout)
    page.wait_for_timeout(200)

def pointer(page, kind, x, y, button=0, pid=1, ptype='mouse'):
    page.dispatch_event('#map', kind, {'button': button, 'pointerId': pid, 'pointerType': ptype, 'clientX': x, 'clientY': y, 'isPrimary': True})

def click_map(page, x, y, button=0, pid=1, move=0):
    pointer(page, 'pointerdown', x, y, button, pid)
    if move: pointer(page, 'pointermove', x + move, y, button, pid)
    pointer(page, 'pointerup', x + move, y, button, pid)
    page.wait_for_timeout(60)

